export const CATEGORY_ICON_NAMES = Object.keys(CATEGORY_ICONS)

export const FALLBACK_ICON: LucideIcon = Tag

/** Own keys only: "constructor" or "toString" must not find Object's prototype. */
export function isKnownIcon(name: string | null | undefined): name is string {
  return typeof name === 'string' && Object.hasOwn(CATEGORY_ICONS, name)
}

export function iconFor(name: string | null | undefined): LucideIcon {
  return isKnownIcon(name) ? CATEGORY_ICONS[name] : FALLBACK_ICON
}
